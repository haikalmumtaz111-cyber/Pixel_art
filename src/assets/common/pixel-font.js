export const GLYPH_HEIGHT = 5;

const glyphOf = (ch) => GLYPHS[ch] || GLYPHS[' '];

// Lebar tulisan dalam piksel (lebar tiap huruf + jarak 1 piksel).
export function textWidth(text) {
  const chars = [...String(text).toUpperCase()];
  return chars.length ? chars.reduce((sum, ch) => sum + glyphOf(ch)[0].length + 1, 0) - 1 : 0;
}

export function drawText(ctx, text, x, y, color) {
  let cx = x;
  for (const ch of String(text).toUpperCase()) {
    const glyph = glyphOf(ch);
    glyph.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '1') rect(ctx, cx + rx, y + ry, 1, 1, color);
    });
    cx += glyph[0].length + 1;
  }
}
